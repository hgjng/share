        for (int i = 0; i < 100; ++i) {
            double mid = (l + r) / 2.0;
            double a = sqrt(max(0.0, x*x - mid*mid));
            double b = sqrt(max(0.0, y*y - mid*mid));
            double h = a*b/(a+b);
            if (h > c) l = mid;
            else r = mid;
        }
